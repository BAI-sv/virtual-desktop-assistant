# 设备接入提示：文案与节流判断（纯 Python 版）
#
#   纯 Python 实现（无外部 DSL 依赖），接口与行为对调用方保持不变。
#
# 调用方：fairy_ball.py 的设备插拔提示块（_mod.设备提示(...)）


def 设备类别(是耳机, 是音箱, 是麦克风, 是键盘, 是存储):
    """把一串布尔特征归成一个类别名（判断顺序：耳机 > 音箱 > 麦克风 > 键鼠 > 存储）。"""
    if 是耳机:
        return '耳机'
    if 是音箱:
        return '音箱'
    if 是麦克风:
        return '麦克风'
    if 是键盘:
        return '键鼠'
    if 是存储:
        return '存储设备'
    return '新设备'


def 设备提示(是新增, 是耳机, 是音箱, 是麦克风, 是键盘, 是存储):
    """根据「是新增还是移除」+ 类别，返回要播报的那句话。

    注意：新增时识别不出类别会给兜底句；移除时【只有耳机/音箱/麦克风】有专句，
    其余统一是「有一个设备已断开」（与原 CNSH 版一致）。
    """
    类别 = 设备类别(是耳机, 是音箱, 是麦克风, 是键盘, 是存储)
    if 是新增:
        if 类别 == '耳机':
            return '检测到耳机已接入'
        if 类别 == '音箱':
            return '音箱已就绪'
        if 类别 == '麦克风':
            return '检测到麦克风已接入'
        if 类别 == '键鼠':
            return '检测到新的输入设备'
        if 类别 == '存储设备':
            return '检测到新的存储设备'
        return '检测到新设备接入'
    if 类别 == '耳机':
        return '耳机已断开'
    if 类别 == '音箱':
        return '音箱已断开'
    if 类别 == '麦克风':
        return '麦克风已断开'
    return '有一个设备已断开'


def 该说(距上次秒数, 已经报过):
    """是否允许播报：已经报过就不再报；距上次不足 20 秒也不报。"""
    if 已经报过:
        return False
    if 距上次秒数 < 20:
        return False
    return True
