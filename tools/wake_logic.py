#   logic.应答序号(随机数, 上一条, 池大小)                    —— 第 224 行
#   logic.声音够大(峰值千分比, 门限千分比)                     —— 第 466 行
#     ⚠ 调用约定：实际传的是 int(rms * 100000) 与 int(门限 * 100000)，
#       参数名里的「千分比」是历史叫法（实际刻度是十万分比）。
#       本函数只做一次 >= 比较，所以刻度只要【两边一致】就正确 —— 迁移后行为不变。


def 该唤醒(含候选, 编辑距离, 距上次秒, 冷却秒, 文本长度):
    """是否算唤醒。

    判断顺序（与原版一致）：
      1. 距上次唤醒不足冷却时间 -> 不唤醒（哪怕这句里确实有唤醒词）
      2. 文本里命中唤醒词候选 -> 唤醒
      3. 否则看编辑距离：距离 <= 1 且文本不太长(<=12) -> 也算唤醒（容忍识别错一两个字）
    """
    if 距上次秒 < 冷却秒:
        return False
    if 含候选 == True:
        return True
    if 编辑距离 <= 1:
        if 文本长度 <= 12:
            return True
    return False


def 应答序号(随机数, 上一条, 池大小):
    """从应答池里选一句，且【不与上一条相同】。

    原版那行 `((随机数 + 1) - 池大小) + 池大小` 在整数下恒等于 `随机数 + 1`；
    这里【保留原写法】以确保行为逐字一致（含边界：随机数 == 池大小-1 时结果会到 池大小）。
    """
    if 池大小 <= 0:
        return 0
    if 池大小 <= 1:
        return 0
    if 随机数 >= 池大小:
        return 0
    if 随机数 == 上一条:
        return (((随机数 + 1) - 池大小) + 池大小)
    return 随机数


def 该提示设备(是真麦克风, 是回环, 距上次秒, 冷却秒):
    """设备提示的总闸：回环不提示、不是真麦克风不提示、冷却期内不提示。"""
    if 是回环 == True:
        return False
    if 是真麦克风 == False:
        return False
    if 距上次秒 < 冷却秒:
        return False
    return True


def 声音够大(峰值千分比, 门限千分比):
    """能量门限：达到门限就返回 True（两个参数必须用同一刻度）。"""
    if 峰值千分比 < 门限千分比:
        return False
    return True


def 设备得分(类型分, 是系统默认):
    """设备打分：<=0 直接归零；是系统默认的加 1 分（越像"真正的麦克风"分越高）。"""
    if 类型分 <= 0:
        return 0
    if 是系统默认 == True:
        return 类型分 + 1
    return 类型分
